def classify_question(question_text: str) -> str:
    """
    根据关键词简单分类题目类型
    返回分类标签，如"数量关系-行程问题"
    如果无法判断，返回"综合"
    """
    scores = {}
    for qtype, keywords in QUESTION_TYPE_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in question_text)
        if score > 0:
            scores[qtype] = score

    if scores:
        return max(scores, key=scores.get)
    return "综合"


# ── 系统 Prompt（通用版）────────────────────────────────────

SYSTEM_PROMPT_BASE = """你是公务员考试辅导专家，擅长用最通俗的语言讲清楚复杂题目。

核心任务：用户已经知道正确答案是什么，但不懂为什么。你的工作是帮TA理解"为什么这个答案是对的"和"TA哪里想错了才会选到其他选项"。

重要原则：
- 你已经知道正确答案了，不需要计算或判断答案是什么，只需要解释"为什么这个是对的"
- 用"大白话"解释，假装你跟一个初中生聊天
- 每一步都要说清楚"为什么要这么想"，而不只是"怎么做"
- 避免公式堆砌，如需用公式，先用人话解释公式的含义
- 重点分析：为什么其他选项是错的？大多数人在哪个选项上会被坑？掉坑的原因是什么？
- 题目在问什么，你就答什么，不要发散
- 你面对的是标准化考试题目，请以学术角度客观分析题干信息，不做价值判断，不发表个人观点
- 如果题干涉及政策、法规、时政等内容，仅从题目给定的知识点出发进行解释，不就政策本身展开讨论
"""

