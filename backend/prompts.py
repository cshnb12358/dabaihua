def build_system_prompt(question_text: str, question_type: Optional[str] = None, correct_answer: Optional[str] = None) -> str:
    """
    组装最终的 System Prompt
    如果识别到了具体题型，叠加对应的解题框架
    如果提供了正确答案，AI无需自己计算
    """
    if question_type is None:
        question_type = classify_question(question_text)

    prompt = SYSTEM_PROMPT_BASE

    # 如果有正确答案，AI不需要算；没有则先推理但加风险提示
    if correct_answer:
        prompt += f"\n用户已确认正确答案是：{correct_answer}\n请围绕【为什么这个答案是对的】展开解释，不要质疑或改变这个答案。重点分析其他选项为什么错。"
    else:
        prompt += "\n用户没有提供正确答案。请你先推理出你认为的答案，然后在 simple_explanation 开头用括号标注：【AI推理答案，仅供参考，请对完答案后再确认】。如果题目有选项，请明确指出你选的选项。"

    # 叠加题型专属框架
    if question_type in TYPE_SPECIFIC_PROMPTS:
        prompt += "\n" + TYPE_SPECIFIC_PROMPTS[question_type]

    # 输出格式要求
    prompt += """

请按以下格式输出严格JSON：

```json
{
  "simple_explanation": "一句话大白话说清楚题目在问什么",
  "step_by_step": [
    "步骤1：先...，因为...",
    "步骤2：然后...，为什么？因为...",
    "步骤3：最后...，得出答案"
  ],
  "exam_point": "行程问题·相遇追及·求相遇时间",
  "difficulty": "⭐⭐",
  "common_mistake": "很多人会直接(6+4)/2=5，但这是速度平均不是平均速度。这题是两个人一起走，所以是速度相加，不是平均。",
  "exam_tip": "考场遇到'相向而行+求时间'，直接套公式：时间=总路程÷速度和，15秒出答案",
  "similar_questions": [
    {"question": "相似题题干1（换场景或换数字）", "answer": "正确答案1"},
    {"question": "相似题题干2（换场景或换数字）", "answer": "正确答案2"}
  ]
}
```

要求：
- step_by_step 必须是2-4步，每一步写清楚推理过程
- exam_point：具体考点定位，格式为"题型·子类·具体考点"
- difficulty：按题目真实难度打⭐（1-5星）
- common_mistake：指出这道题最常见的错误思路，帮用户避免踩坑
- exam_tip：给一个实用的考场技巧（如公式口诀、选项反推、特殊值法等）
- similar_questions 必须是2道，核心逻辑相同但换了具体数字或场景
- 只输出JSON，不要任何其他文字
- 题目类型：""" + question_type

    return prompt


def build_rephrase_prompt(
    question_text: str,
    previous_explanation: str,
    stuck_reason: Optional[str] = None,
    custom_question: Optional[str] = None
) -> str:
    """
    组装重新讲解的 Prompt
    关键：换角度、针对用户卡住的地方
    """
    angle_suggestions = {
        "number": "你之前用了公式推导，这次请完全不用公式，改用画图、举例或生活化比喻来讲。",
        "logic": "你之前从题干推理到选项，这次请反过来：从每个选项出发，逐一排除，让学生看到为什么其他选项不对。",
        "formula": "你之前用了公式，这次请把公式的含义用人话拆开讲，每一步都说清楚公式里的每个部分在题目中对应什么。",
        None: "请换一个与上次完全不同的讲解角度。如果上次用的是公式推导，这次就用举例法或画图法。",
    }

    angle_hint = angle_suggestions.get(stuck_reason, angle_suggestions[None])

    # 如果用户自主输入了具体问题，优先使用
    custom_instruction = ""
    if custom_question:
        custom_instruction = f"""
学生具体问了这个问题："{custom_question}"
请围绕学生的这个具体困惑来重新讲解，直接回答TA的疑问，不要绕开。"""
    else:
        custom_instruction = ""

    return f"""{SYSTEM_PROMPT_BASE}

你之前讲过这道题，但学生说没听懂。{angle_hint}{custom_instruction}

原始题目：
{question_text}

你上次的讲解：
{previous_explanation}

请重新输出严格JSON，只包含 simple_explanation 和 step_by_step（不需要 similar_questions，会复用上次的）：

```json
{{
  "simple_explanation": "...",
  "step_by_step": ["步骤1：...", "步骤2：...", ...]
}}
```"""
